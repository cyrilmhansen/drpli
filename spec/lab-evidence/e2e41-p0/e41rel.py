#!/usr/bin/env python3
"""e41rel.py -- decode DR's FILE-OPEN code regions out of authentic objects.

Usage:
    python3 spec/lab-evidence/e2e41-p0/e41rel.py ENTER [UPDATE ...]
    python3 spec/lab-evidence/e2e41-p0/e41rel.py --all

For one historical program it prints, from three INDEPENDENT authentic artifacts:

  * the OPEN statements, with their exact source lines  (artefacts/<P>.PLI)
  * the code region each one occupies, taken from DR's own per-line code
    addresses in the compile listing                    (golden/first8080u/<P>/<P>.PRN)
  * the linked image of that region, where every operand is a resolved
    address                                             (golden/link1/<P>.COM)
  * the record stream that produced it: SEL-COMMON / RELOC / CHAIN-EXT
    with the code slot each external is chained at      (golden/first8080u/<P>/<P>.REL)
  * the LINK map, which names the COMMON groups and gives the segment ranges
    DR's linker assigned                                (golden/link1/link-batch*.txt)

The last two are what make the third readable: a bare `LXI H,1F40' in a .COM
is meaningless until you know whether 1F40 is inside CODE, DATA or a named
COMMON group.  Everything printed here is decoded from files already committed
as DR output; NOTHING is generated by this compiler.

Operand classification is deliberately conservative: a value is called a
control block only if the LINK map names a COMMON group at that exact address,
a string only if the bytes at it are printable and length-prefixed, and
otherwise IMMEDIATE/UNKNOWN.  Guessing a role for a number is exactly the
mistake [C264] warns about.
"""
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
sys.path.insert(0, os.path.join(ROOT, 'tools'))
from reldump import BR, SEGS, TYPES          # noqa: E402  (the pinned decoder)

PRN_ADDR = re.compile(r'^\s*(\d+)\s+([a-e])\s+([0-9A-F]{4})\s+(.*)$')


def open_stmts(path):
    """(first_line, last_line, text) for every statement whose head is OPEN."""
    src = open(path, errors='replace').read().replace('\r\n', '\n')
    out, cur, start = [], [], None
    for i, line in enumerate(src.split('\n'), 1):
        t = line.strip()
        if start is None and re.match(r'(?i)^open\b', t):
            start = i
        if start is not None:
            cur.append(t)
            if ';' in t:
                out.append((start, i, ' '.join(cur)))
                cur, start = [], None
    return out


def line_addrs(prn):
    """source line -> code address DR had reached at the END of that line."""
    m = {}
    for raw in open(prn, errors='replace'):
        g = PRN_ADDR.match(raw.rstrip('\n'))
        if g:
            m[int(g.group(1))] = int(g.group(3), 16)
    return m


def link_map(prog):
    """Find DR's LINK output for PROG and return (code_lo, code_hi, data_lo,
    data_hi, [(common_name, addr)]) -- parsed from the authentic transcript."""
    best = None
    for fn in sorted(os.listdir(os.path.join(ROOT, 'golden', 'link1'))):
        if not fn.endswith('.transcript.txt'):
            continue
        txt = open(os.path.join(ROOT, 'golden', 'link1', fn),
                   errors='replace').read().replace('\r\n', '\n')
        for blk in txt.split('>>> ')[::-1]:
            if not blk.startswith('LINK ') and not blk.startswith('L:'):
                continue
            head = blk.split('\n', 1)[0]
            if not re.search(r'(?i)\b' + re.escape(prog) + r'\s*$', head):
                continue
            m = re.search(r'CODE SIZE\s+([0-9A-F]{4}) \(([0-9A-F]{4})-([0-9A-F]{4})\)', blk)
            d = re.search(r'DATA SIZE\s+([0-9A-F]{4}) \(([0-9A-F]{4})-([0-9A-F]{4})\)', blk)
            syms = [(n, int(a, 16)) for n, a in
                    re.findall(r'/([A-Z0-9_$]+)/\s+([0-9A-F]{4})', blk)]
            if m and d:
                best = (int(m.group(2), 16), int(m.group(3), 16),
                        int(d.group(2), 16), int(d.group(3), 16), syms)
    return best


def rel_stream(rel):
    """Replay the bitstream, keeping the slot ADDRESS of every RELOC (which
    tools/reldump.py's item list drops) and the name of every CHAIN-EXT."""
    d = open(rel, 'rb').read()
    br = BR(d)
    seg, addr = 'code', 0
    ev = []
    common_bytes, code_bytes, data_bytes = {}, {}, {}
    while True:
        try:
            if br.bit() == 0:
                b = br.bits(8)
                {'code': code_bytes, 'data': data_bytes, 'common': common_bytes}[seg][addr] = b
                ev.append(('DATA', seg, addr, b))
                addr += 1
                continue
            cls = br.bits(2)
            if cls:
                v = br.val16()
                ev.append(('RELOC', seg, addr, (SEGS[cls], v)))
                addr += 2
                continue
            t = br.bits(4)
            val = nm = None
            if 5 <= t <= 14:
                s = br.bits(2)
                val = ('abs', br.val16()) if s == 0 else (SEGS[s], br.val16())
            if t <= 7:
                n = br.bits(3)
                nm = ''.join(chr(br.bits(8)) for _ in range(n))
            if t == 14:
                br.pad()
            if t == 11 and val:
                seg, addr = val[0], val[1]
            ev.append(('LINK-' + TYPES[t], None, val, nm))
            if t == 15:
                break
        except EOFError:
            break
    return ev, code_bytes, data_bytes, common_bytes


def classify(v, cmap, cm, com_bytes):
    """Name a 16-bit value using DR's own LINK map."""
    if cm:
        c_lo, c_hi, d_lo, d_hi, syms = cm
        for nm, a in syms:
            if a == v:
                return 'COMMON group /%s/' % nm
        if d_lo <= v <= d_hi:
            raw = com_bytes.get('data', {})
            body = bytes(raw.get(v + i, 0) for i in range(0, 24))
            txt = ''.join(chr(b) if 32 <= b < 127 else '.' for b in body)
            return 'DATA cell (bytes %s | %r)' % (
                ' '.join('%02X' % raw.get(v + i, 0) for i in range(8)), txt)
        if c_lo <= v <= c_hi:
            return 'CODE-segment address (tail/pool)'
    return 'IMMEDIATE value %d' % v


def main():
    args = sys.argv[1:]
    ALL = ['ENTER', 'UPDATE', 'COPY', 'KEYFILE', 'REPORT', 'RETRIEVE']
    progs = ALL if args == ['--all'] else (args or ['ENTER'])
    for prog in progs:
        src = os.path.join(ROOT, 'artefacts', prog + '.PLI')
        prn = os.path.join(ROOT, 'golden', 'first8080u', prog, prog + '.PRN')
        rel = os.path.join(ROOT, 'golden', 'first8080u', prog, prog + '.REL')
        com = os.path.join(ROOT, 'golden', 'link1', prog + '.COM')
        if not os.path.exists(src):
            print('%s: no source' % prog)
            continue
        print('=' * 72)
        print(prog, '  source', src.replace(ROOT + '/', ''))
        ops = open_stmts(src)
        la = line_addrs(prn)
        cm = link_map(prog)
        ev, code_b, data_b, common_b = rel_stream(rel)
        print('  DR LINK map:', ('CODE %04X-%04X DATA %04X-%04X COMMON %s' % (
            cm[0], cm[1], cm[2], cm[3],
            ', '.join('/%s/=%04X' % (n, a) for n, a in cm[4]))) if cm else 'NOT FOUND')
        # external chains, keyed by code slot
        ext = {}
        for k, seg_, a_, v_ in ev:
            if k == 'LINK-CHAIN-EXT':
                ext[a_[1]] = v_
        print('  external chains (code slot -> PLILIB symbol):')
        for a_ in sorted(ext):
            print('     %04X  %s' % (a_, ext[a_]))
        for (l0, l1, text) in ops:
            start = la.get(l0 - 1, None)
            end = la.get(l1, None)
            print('  ---- OPEN at source lines %d-%d' % (l0, l1))
            print('       %s' % text)
            if start is None or end is None or end <= start:
                print('       (PRN line addresses unavailable: %r..%r)' % (start, end))
                continue
            print('       code region %04X..%04X  (%d bytes)' % (start, end - 1, end - start))
            # The .REL view FIRST: which operands are RELOC records and which are
            # plain DATA bytes.  A linked .COM shows both as a 16-bit number, and
            # reading that number as an address (or as a constant) is [C264]'s trap.
            rmap = {}
            for k, seg_, a_, v_ in ev:
                if k == 'RELOC' and seg_ == 'code':
                    rmap[a_] = v_
            cb = {}
            for k, seg_, a_, v_ in ev:
                if k == 'DATA' and seg_ == 'code':
                    cb[a_] = v_
            print('       .REL operands in this region:')
            i2 = start
            while i2 < end:
                if i2 in rmap:
                    tg, vv = rmap[i2]
                    print('         %04X  RELOC -> %s 0x%X' % (i2, tg, vv))
                    i2 += 2
                else:
                    i2 += 1
            out = subprocess.run(
                [sys.executable, os.path.join(ROOT, 'tools', 'dis80.py'), '--com', com,
                 '%04X' % (start + 0x100), '%04X' % (end + 0x100)],
                capture_output=True, text=True).stdout
            for line in out.rstrip('\n').split('\n'):
                g = re.match(r'^([0-9A-F]{4})\s+(\S+ ?\S*)\s+(?:([0-9A-F]{4}))?\s*;(.*)$', line)
                if g:
                    a = int(g.group(1), 16) - 0x100
                    note = ''
                    mn = g.group(2).strip()
                    if mn.startswith('CALL') and a + 2 in ext:
                        note = '   ; -> %s' % ext[a + 2]
                    if mn.startswith('CALL') and g.group(3):
                        note = '   ; -> %s (address %s, PLILIB)' % (ext.get(a + 2, '?'), g.group(3))
                    if mn.startswith('LXI') and g.group(3):
                        v = int(g.group(3), 16)
                        note = '   ; operand classifies as: %s' % classify(
                            v, None, cm, {'data': data_b, 'common': common_b, 'code': code_b})
                    print('       ' + line + note)
                elif line.strip():
                    print('       ' + line)
        print()


if __name__ == '__main__':
    main()


def replay(rel):
    """Replay a .REL bitstream into the shapes an argument-block decoder needs.

    Returns (events, code_bytes, rmap, ext, common_layout, common_total) where

      rmap          {code_address: ('data'|'common'|..., target_index)}
                    -- the RELOC attached to each code byte; a code slot with no
                    entry here holds a compile-time CONSTANT, which is the whole
                    difference between `1F40' as B(8000) and `1F40' as an address
                    [C264].
      ext           {chain-ext slot address: '?ROUTINE'}  -- the anchor a block is
                    found from: DR's LINK-CHAIN-EXT record names the routine.
      common_layout [(group name, first merged index, size)] in DR's own link order,
                    which is what turns a `RELOC->common 0x0' into /EMP/.
      common_total  bytes of COMMON the object declares.
    """
    br = BR(open(rel, 'rb').read())
    seg, addr = 'code', 0
    code_b, ev = {}, []
    ext, rmap = {}, {}
    layout, run, cur = [], 0, None
    while True:
        try:
            if br.bit() == 0:
                if seg == 'code':
                    code_b[addr] = br.bits(8)
                else:
                    br.bits(8)
                addr += 1
                continue
            cls = br.bits(2)
            if cls:
                v = br.val16()
                # A COMMON reloc's address is GROUP-RELATIVE; the group is the one the
                # most recent SEL-COMMON selected, not something the reloc itself says.
                tgt = (SEGS[cls], v, cur if SEGS[cls] == 'common' else None)
                ev.append(('RELOC', seg, addr, tgt))
                if seg == 'code':
                    rmap[addr] = tgt
                addr += 2
                continue
            t = br.bits(4)
            val = nm = None
            if 5 <= t <= 14:
                s = br.bits(2)
                val = ('abs', br.val16()) if s == 0 else (SEGS[s], br.val16())
            if t <= 7:
                n = br.bits(3)
                nm = ''.join(chr(br.bits(8)) for _ in range(n))
            if t == 14:
                br.pad()
            if t == 11 and val:
                seg, addr = val[0], val[1]
            if t == 5:                        # DEF-COMMON-SIZE: a named COMMON group
                size = val[1] if val else 0
                layout.append((nm, run, size))
                run += size
            elif t == 1:                      # SEL-COMMON: the group code refers to
                cur = nm
            elif t == 6:                      # CHAIN-EXT: (slot address, '?ROUTINE')
                ext[val[1]] = nm
            ev.append(('LINK-' + TYPES[t], None, val, nm))
            if t == 15:
                break
        except EOFError:
            break
    n = max(code_b, default=-1) + 1
    return (ev, bytes(code_b.get(i, 0) for i in range(n)), rmap, ext, layout, run)


def common_at(layout, idx):
    """(group name, offset in group) owning merged COMMON index `idx'."""
    for nm, start, size in layout:
        if start <= idx < start + size:
            return nm, idx - start
    return None, None
